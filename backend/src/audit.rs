//! Audit trail primitives: HMAC signing, key parsing and retention.
//!
//! The HTTP handlers live in [`crate::api::audit`]; this module holds the pure
//! helpers shared by the server, the CLI and the tests, so the exact bytes an
//! export signs can be reproduced without a running control plane.
//!
//! ## Export signature
//!
//! `GET /api/audit/export` returns JSON Lines and proves integrity with
//! `X-Fleett-Signature: sha256=<hex HMAC-SHA256(body)>`. The key comes from
//! `FLEETT_AUDIT_HMAC_KEY`; without one the endpoint refuses with `409
//! audit_key_missing` instead of exporting unverifiable evidence.
//!
//! ## Key formats
//!
//! The key is accepted as hexadecimal or raw text:
//!
//! * `hex:<digits>` decodes the digits, and an invalid value is an error;
//! * `raw:<text>` uses the UTF-8 bytes as-is;
//! * without a prefix an even-length string made only of hex digits is decoded
//!   (the common case: a 64-character key generated by `openssl rand -hex 32`);
//! * anything else is used as raw UTF-8 bytes.
//!
//! ## Retention
//!
//! `FLEETT_AUDIT_RETENTION` accepts `30d` (days), `24h` (hours) or a bare
//! integer read as days. The default is 90 days.

use hmac::{Hmac, Mac};
use sha2::Sha256;

/// Environment variable holding the export HMAC key.
pub const HMAC_KEY_VAR: &str = "FLEETT_AUDIT_HMAC_KEY";
/// Environment variable holding the retention window.
pub const RETENTION_VAR: &str = "FLEETT_AUDIT_RETENTION";
/// Prefix of the `X-Fleett-Signature` header value.
pub const SIGNATURE_PREFIX: &str = "sha256=";
/// Retention applied when the variable is unset.
pub const DEFAULT_RETENTION: &str = "90d";

/// Export signing key, kept opaque so `Config`'s `Debug` never leaks it.
#[derive(Clone, PartialEq, Eq)]
pub struct AuditKey(Vec<u8>);

impl AuditKey {
    pub fn new(bytes: Vec<u8>) -> Self {
        Self(bytes)
    }

    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }
}

impl std::fmt::Debug for AuditKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("AuditKey(<redacted>)")
    }
}

/// Parse a configured HMAC key (hex or raw, see the module docs).
pub fn parse_key(raw: &str) -> Result<Vec<u8>, String> {
    let value = raw.trim();
    if value.is_empty() {
        return Err("the key is empty".to_string());
    }
    if let Some(hex) = value.strip_prefix("hex:") {
        return decode_hex(hex.trim()).map_err(|err| format!("invalid hex key: {err}"));
    }
    if let Some(text) = value.strip_prefix("raw:") {
        if text.is_empty() {
            return Err("the key is empty".to_string());
        }
        return Ok(text.as_bytes().to_vec());
    }
    if is_hex(value) {
        return decode_hex(value).map_err(|err| format!("invalid hex key: {err}"));
    }
    Ok(value.as_bytes().to_vec())
}

/// Hex HMAC-SHA256 of `body` with `key`, without the `sha256=` prefix.
pub fn sign(key: &[u8], body: &[u8]) -> String {
    let mut mac = Hmac::<Sha256>::new_from_slice(key).expect("HMAC accepts any key size");
    mac.update(body);
    encode_hex(&mac.finalize().into_bytes())
}

/// Full `X-Fleett-Signature` value (`sha256=<hex>`).
pub fn signature_header(key: &[u8], body: &[u8]) -> String {
    format!("{SIGNATURE_PREFIX}{}", sign(key, body))
}

/// Parse `FLEETT_AUDIT_RETENTION` (`30d`, `24h` or an integer number of days).
pub fn parse_retention(raw: &str) -> Result<chrono::Duration, String> {
    let value = raw.trim().to_ascii_lowercase();
    if value.is_empty() {
        return Err("the retention is empty".to_string());
    }
    let (number, unit) = match value.strip_suffix('d') {
        Some(number) => (number, "days"),
        None => match value.strip_suffix('h') {
            Some(number) => (number, "hours"),
            None => (value.as_str(), "days"),
        },
    };
    let amount: i64 = number
        .trim()
        .parse()
        .map_err(|_| format!("expected 30d, 24h or a number of days, got \"{raw}\""))?;
    if amount <= 0 {
        return Err("the retention must be greater than zero".to_string());
    }
    let seconds = match unit {
        "hours" => amount.saturating_mul(3600),
        _ => amount.saturating_mul(86_400),
    };
    if seconds <= 0 {
        return Err("the retention is too large".to_string());
    }
    Ok(chrono::Duration::seconds(seconds))
}

/// Canonical label of a retention window (`90d`, `36h`…), for reports.
pub fn retention_label(retention: chrono::Duration) -> String {
    let seconds = retention.num_seconds();
    if seconds % 86_400 == 0 {
        format!("{}d", seconds / 86_400)
    } else if seconds % 3_600 == 0 {
        format!("{}h", seconds / 3_600)
    } else {
        format!("{seconds}s")
    }
}

/// True when `value` is a non-empty even-length run of hex digits.
pub fn is_hex(value: &str) -> bool {
    !value.is_empty() && value.len() % 2 == 0 && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

/// Lowercase hex encoding (2 characters per byte).
pub fn encode_hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        let _ = write!(out, "{byte:02x}");
    }
    out
}

/// Decode a hex string (even length required).
pub fn decode_hex(text: &str) -> Result<Vec<u8>, String> {
    if text.len() % 2 != 0 {
        return Err("an odd number of digits".to_string());
    }
    let mut out = Vec::with_capacity(text.len() / 2);
    let bytes = text.as_bytes();
    for pair in bytes.chunks_exact(2) {
        let high = hex_digit(pair[0])?;
        let low = hex_digit(pair[1])?;
        out.push((high << 4) | low);
    }
    Ok(out)
}

fn hex_digit(byte: u8) -> Result<u8, String> {
    match byte {
        b'0'..=b'9' => Ok(byte - b'0'),
        b'a'..=b'f' => Ok(byte - b'a' + 10),
        b'A'..=b'F' => Ok(byte - b'A' + 10),
        _ => Err(format!("invalid digit {:?}", char::from(byte))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_hex_or_raw_and_remember_the_prefix() {
        // 32 bytes of 0xab, the shape of `openssl rand -hex 32`.
        let hex = "ab".repeat(32);
        assert_eq!(parse_key(&hex).expect("hex"), vec![0xabu8; 32]);
        assert_eq!(
            parse_key(&format!("hex:{hex}")).expect("explicit hex"),
            vec![0xabu8; 32]
        );
        assert_eq!(
            parse_key("raw:0123456789abcdef").expect("explicit raw"),
            b"0123456789abcdef".to_vec()
        );
        assert_eq!(
            parse_key("not-hex-key").expect("raw"),
            b"not-hex-key".to_vec()
        );
        // Odd length cannot be hex, so it stays raw.
        assert_eq!(parse_key("abc").expect("raw"), b"abc".to_vec());
        assert!(parse_key("").is_err());
        assert!(parse_key("hex:xyz0").is_err());
    }

    #[test]
    fn signatures_are_stable_and_prefixed() {
        // RFC 4231 test case 2, key "Jefe".
        let signature = sign(b"Jefe", b"what do ya want for nothing?");
        assert_eq!(
            signature,
            "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"
        );
        assert_eq!(
            signature_header(b"Jefe", b"what do ya want for nothing?"),
            format!("sha256={signature}")
        );
    }

    #[test]
    fn retention_accepts_days_hours_and_bare_integers() {
        assert_eq!(
            parse_retention("30d").expect("days"),
            chrono::Duration::days(30)
        );
        assert_eq!(
            parse_retention("24h").expect("hours"),
            chrono::Duration::hours(24)
        );
        assert_eq!(
            parse_retention("90").expect("bare days"),
            chrono::Duration::days(90)
        );
        assert_eq!(
            parse_retention(DEFAULT_RETENTION).expect("default"),
            chrono::Duration::days(90)
        );
        for invalid in ["", "0", "0d", "-2d", "10m", "forever"] {
            assert!(parse_retention(invalid).is_err(), "{invalid}");
        }
        assert_eq!(retention_label(chrono::Duration::days(90)), "90d");
        assert_eq!(retention_label(chrono::Duration::hours(36)), "36h");
    }

    #[test]
    fn hex_round_trips() {
        let bytes = [0u8, 1, 15, 16, 127, 128, 254, 255];
        assert_eq!(encode_hex(&bytes), "00010f107f80feff");
        assert_eq!(decode_hex("00010f107f80feff").expect("decode"), bytes);
        assert!(decode_hex("abc").is_err());
        assert!(decode_hex("zz").is_err());
    }
}
