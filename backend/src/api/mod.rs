#[cfg(feature = "embed-web")]
#[derive(rust_embed::Embed)]
#[folder = "../web/dist/"]
struct WebAssets;

#[allow(dead_code)]
/// Cache policy for the embedded frontend.
///
/// The service worker, the manifest and the offline page must never be cached
/// by the HTTP layer, otherwise a new release can take an hour to be picked up.
/// Vite emits content-hashed files under `assets/`, safe to cache forever.
fn cache_control(requested: &str) -> &'static str {
    if matches!(
        requested,
        "index.html" | "sw.js" | "manifest.webmanifest" | "offline.html"
    ) {
        "no-cache"
    } else if requested.starts_with("assets/") {
        "public, max-age=31536000, immutable"
    } else if requested.contains('.') {
        "public, max-age=3600"
    } else {
        "no-cache"
    }
}

#[cfg(feature = "embed-web")]
async fn embedded_asset(uri: axum::http::Uri) -> axum::response::Response {
    use axum::http::header;
    use axum::response::IntoResponse;

    let requested = uri.path().trim_start_matches('/');
    let requested = if requested.is_empty() {
        "index.html"
    } else {
        requested
    };
    let Some(file) = WebAssets::get(requested).or_else(|| WebAssets::get("index.html")) else {
        return ApiError::not_found("the embedded frontend is empty").into_response();
    };
    let cache = cache_control(requested);
    (
        [
            (header::CONTENT_TYPE, content_type(requested)),
            (header::CACHE_CONTROL, cache),
        ],
        file.data.into_owned(),
    )
        .into_response()
}

#[cfg(feature = "embed-web")]
fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or_default() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "txt" => "text/plain; charset=utf-8",
        "webmanifest" => "application/manifest+json",
        _ => "application/octet-stream",
    }
}

/// Write the compose file from the current spec and run `up -d`.
///
/// The stored egress policy is probed first: recreating a container that would
/// point at a dead proxy is refused with `422 proxy_unreachable` (issue #60).
pub(crate) async fn apply_compose(
    state: &AppState,
    spec: &mut InstanceSpec,
) -> Result<(), ApiError> {
    crate::api::hydrate_previous_image(state, spec);
    crate::api::egress::ensure_egress_proxy(state, spec).await?;
    write_compose_file(state, spec)?;
    up_and_record(state, spec).await
}

/// Write `instances/<id>/compose.yaml` from the spec, without touching Docker.
///
/// The declared project is kept (an instance created by an older release stays
/// on `hermes-<id>`), and every environment variable is re-declared as
/// `${KEY}` so the driver keeps injecting the values at runtime.
pub(crate) fn write_compose_file(state: &AppState, spec: &InstanceSpec) -> Result<(), ApiError> {
    let project = store::declared_project(&state.cfg, &spec.id);
    let keys = compose_env_keys(state, spec)?;
    let policy = crate::egress_policy::load(&state.db, &spec.id).map_err(ApiError::from)?;
    let compose = crate::render::render_compose_with_project_and_policy(
        &state.cfg,
        spec,
        project.as_deref(),
        &keys,
        policy.as_ref(),
    )
    .map_err(ApiError::from)?;
    store::write_compose(&state.cfg, &spec.id, &compose)
        .map_err(|err| ApiError::internal(format!("failed to write compose file: {err}")))
}

/// Environment variable names the compose file must declare as `${KEY}`.
///
/// Every stored instance variable, plus the provider key when a provider is
/// attached: the provider secret is injected by the driver and never stored as
/// a row, but the compose document still has to interpolate its variable.
pub(crate) fn compose_env_keys(
    state: &AppState,
    spec: &InstanceSpec,
) -> Result<Vec<String>, ApiError> {
    let mut keys = crate::envs::keys(&state.cfg, &state.db, &spec.id).map_err(ApiError::from)?;
    push_provider_key(&mut keys, spec);
    Ok(keys)
}

/// Append the provider key to a variable-name list (no-op without a provider).
pub(crate) fn push_provider_key(keys: &mut Vec<String>, spec: &InstanceSpec) {
    if spec.provider.is_some() && !keys.iter().any(|key| key == &spec.api_key_env) {
        keys.push(spec.api_key_env.clone());
    }
}

/// Carry the `fleett.previous_image` label of the compose file into the spec
/// before a rewrite, so a PATCH never drops the upgrade history.
pub(crate) fn hydrate_previous_image(state: &AppState, spec: &mut InstanceSpec) {
    if spec.previous_image.is_none() {
        spec.previous_image = store::previous_image(&state.cfg, &spec.id);
    }
}

/// `docker compose up -d`, then record the resulting status.
pub(crate) async fn up_and_record(
    state: &AppState,
    spec: &mut InstanceSpec,
) -> Result<(), ApiError> {
    match state.driver.up(spec).await {
        Ok(()) => {
            let observed = state.driver.ps(spec).await.ok();
            let status = observed
                .as_ref()
                .map(|result| result.status)
                .unwrap_or(Status::Running);
            let health = observed
                .as_ref()
                .map(|result| result.health)
                .unwrap_or(Health::Unknown);
            let last_error = match health {
                Health::Unhealthy => Some(HEALTH_UNHEALTHY_MESSAGE),
                _ => None,
            };
            spec.status = status;
            spec.last_error = last_error.map(str::to_string);
            state
                .db
                .set_status(&spec.id, status, last_error)
                .map_err(ApiError::from)?;
            state
                .metrics
                .record_compose_action("up", crate::metrics::RESULT_OK);
            // `write_instance`/`write_compose` may have regenerated
            // `config.yaml`: record it as a `sync:` commit before returning.
            if let Err(err) = crate::history::reconcile(&state.cfg, &spec.id) {
                tracing::warn!(instance = %spec.id, %err, "could not reconcile the instance history");
            }
            Ok(())
        }
        Err(err) => {
            let detail = err.detail.clone();
            spec.status = Status::Error;
            let _ = state.db.set_status(&spec.id, Status::Error, Some(&detail));
            state
                .metrics
                .record_compose_action("up", crate::metrics::RESULT_ERROR);
            Err(ApiError::driver(err))
        }
    }
}

#[cfg(test)]
mod cache_tests {
    use super::cache_control;

    #[test]
    fn shell_files_are_never_cached() {
        for path in [
            "index.html",
            "sw.js",
            "manifest.webmanifest",
            "offline.html",
        ] {
            assert_eq!(cache_control(path), "no-cache", "{path}");
        }
    }

    #[test]
    fn hashed_assets_are_immutable() {
        assert_eq!(
            cache_control("assets/index-abc123.js"),
            "public, max-age=31536000, immutable"
        );
    }

    #[test]
    fn other_static_files_keep_a_short_cache() {
        assert_eq!(cache_control("icons/icon-192.png"), "public, max-age=3600");
        assert_eq!(cache_control("favicon.svg"), "public, max-age=3600");
        assert_eq!(cache_control("some/route"), "no-cache");
    }
}
