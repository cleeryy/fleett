/// Timeout of one outbound notification HTTP call.
pub const NOTIFY_HTTP_TIMEOUT: std::time::Duration = std::time::Duration::from_secs(15);

/// Shared state of every handler.
#[derive(Clone)]
pub struct AppState {
    pub cfg: Arc<Config>,
    pub db: Db,
    pub driver: Arc<dyn Driver>,
    pub auth: Arc<AuthService>,
    pub locks: Arc<InstanceLocks>,
    /// Last (or running) rolling upgrade (`POST /api/upgrade`).
    pub upgrade: Arc<upgrade::UpgradeManager>,
    /// Prometheus counters and the cached utilisation sample (`GET /metrics`).
    pub metrics: Arc<crate::metrics::Metrics>,
    /// Watchdog sampling state (streaks, heal attempts, backoff).
    pub watchdog: Arc<crate::watchdog::WatchdogState>,
    /// Persistent searchable log center (`GET /api/logs`).
    pub logstore: Arc<crate::logstore::LogStore>,
    /// Effective command policy of `POST /api/instances/{id}/exec`.
    pub exec_policy: Arc<crate::exec::ExecPolicy>,
    /// Ingestion budget of `POST /api/egress/blocks`.
    pub block_ingest: Arc<egress::BlockRateLimiter>,
    /// Cached reachability of the rendered egress proxies (`GET …/egress`).
    pub egress_probe: Arc<crate::egress_policy::ProxyProbeCache>,
    /// Rate limiter and progressive authentication lockout.
    pub security: Arc<crate::security::Security>,
    /// Shared HTTP client of the outbound notifications (and nothing else):
    /// one connection pool, one timeout, no per-alert client.
    pub http: reqwest::Client,
    /// Last disk-quota level of every instance (one event per crossing).
    pub quota: Arc<crate::quota::QuotaMonitor>,
    /// In-memory token counters of the integrated assistant, one per session.
    pub assistant: Arc<crate::assistant::Sessions>,
    /// Marketplace catalogue (issue #61): providers, caches and rate limits.
    pub marketplace: Arc<crate::marketplace::Marketplace>,
    pub started_at: Instant,
}

impl AppState {
    /// Open the database, rebuild the index from the filesystem and return the
    /// ready state.
    pub fn bootstrap(cfg: Config, driver: Arc<dyn Driver>) -> anyhow::Result<Self> {
        let db = Db::open(&cfg.db_path())?;
        Self::bootstrap_with_db(cfg, driver, db)
    }

    /// Same as [`AppState::bootstrap`] with an already open database, so the
    /// compose driver and the state share one connection pool.
    pub fn bootstrap_with_db(cfg: Config, driver: Arc<dyn Driver>, db: Db) -> anyhow::Result<Self> {
        let auth = AuthService::from_config(&cfg);
        Self::bootstrap_with_db_and_auth(cfg, driver, db, auth)
    }

    /// Bootstrap with an explicit [`AuthService`] (tests inject fake OIDC
    /// verifiers this way).
    pub fn bootstrap_with_db_and_auth(
        cfg: Config,
        driver: Arc<dyn Driver>,
        db: Db,
        auth: AuthService,
    ) -> anyhow::Result<Self> {
        store::ensure_layout(&cfg)?;
        // Rebuild the template index from `templates/<id>/`: the files are the
        // source of truth, the database only lists and versions them.
        if let Err(err) = crate::templates::reindex(&cfg, &db) {
            tracing::warn!(%err, "could not index the custom templates");
        }
        db::reconcile(&cfg, &db)?;
        // Import the pre-0.5 encrypted secret maps into `instance_env` (idempotent;
        // a missing key only logs a warning and leaves them readable in place).
        crate::envs::migrate_sealed(&cfg, &db);
        // Record the changes made outside the API since the last run (a file
        // edited over SSH, a config regenerated by an older release).
        crate::history::reconcile_all(&cfg);
        // Drop expired restore points before serving (idempotent, best effort).
        crate::snapshots::startup(&cfg, &db);
        let exec_policy = crate::exec::ExecPolicy::from_config(cfg.exec_allowlist.as_deref());
        let logstore = Arc::new(crate::logstore::LogStore::from_config(&cfg));
        // Build the limiter before `cfg` is moved into the state.
        let security = crate::security::Security::new(cfg.security.clone());
        // Build the catalogue before `cfg` is moved into the state: its HTTP
        // client embeds the download policy (HTTPS, loopback, insecure flag).
        let marketplace = Arc::new(crate::marketplace::Marketplace::from_config(&cfg));
        Ok(Self {
            cfg: Arc::new(cfg),
            db,
            driver,
            auth: Arc::new(auth),
            locks: Arc::new(InstanceLocks::default()),
            upgrade: Arc::new(upgrade::UpgradeManager::default()),
            metrics: Arc::new(crate::metrics::Metrics::new()),
            watchdog: Arc::new(crate::watchdog::WatchdogState::default()),
            exec_policy: Arc::new(exec_policy),
            logstore,
            security: Arc::new(security),
            block_ingest: Arc::new(egress::BlockRateLimiter::default()),
            egress_probe: Arc::new(crate::egress_policy::ProxyProbeCache::default()),
            http: reqwest::Client::builder()
                .timeout(NOTIFY_HTTP_TIMEOUT)
                .build()
                .unwrap_or_default(),
            quota: Arc::new(crate::quota::QuotaMonitor::new()),
            assistant: Arc::new(crate::assistant::Sessions::default()),
            marketplace,
            started_at: Instant::now(),
        })
    }
}

/// One async mutex per instance id, so lifecycle operations on the same
/// instance never interleave.
#[derive(Default)]
pub struct InstanceLocks {
    inner: Mutex<HashMap<String, Arc<AsyncMutex<()>>>>,
}

impl InstanceLocks {
    pub fn for_id(&self, id: &str) -> Arc<AsyncMutex<()>> {
        let mut map = self
            .inner
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        map.entry(id.to_string()).or_default().clone()
    }
}

/// Build the full application router.
pub fn router(state: AppState) -> Router {
    let api = api_routes(state.clone());
    finalize(api, auth_pages(), state.clone())
        // Innermost first: the limiter sees every request, the request counter
        // sees the 429 the limiter produces, the headers close every response.
        .layer(middleware::from_fn_with_state(
            state.clone(),
            crate::security::guard,
        ))
        .layer(middleware::from_fn_with_state(
            state.clone(),
            crate::metrics::track_request,
        ))
        .layer(middleware::from_fn_with_state(
            state,
            crate::security::headers,
        ))
}

