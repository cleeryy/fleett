    #[test]
    fn healthcheck_script_reports_the_gateway_answer() {
        // The shipped script targets /opt/data/gateway.sock; the test swaps in
        // a throwaway socket path and runs the real interpreter against a fake
        // control socket.
        if std::process::Command::new("python3")
            .arg("--version")
            .output()
            .is_err()
        {
            eprintln!("python3 unavailable, skipping the probe run");
            return;
        }

        fn run_probe(reply: &'static str) -> bool {
            use std::io::{BufRead, BufReader, Write};
            use std::os::unix::net::UnixListener;

            let dir = tempfile::tempdir().expect("temp dir");
            let socket_path = dir.path().join("gateway.sock");
            let script_path = dir.path().join("healthcheck.py");
            let script = HEALTHCHECK_SCRIPT.replace(
                "SOCKET_PATH = \"/opt/data/gateway.sock\"",
                &format!(
                    "SOCKET_PATH = {:?}",
                    socket_path.to_str().expect("utf-8 socket path")
                ),
            );
            std::fs::write(&script_path, script).expect("write script");

            let listener = UnixListener::bind(&socket_path).expect("bind fake socket");
            let server = std::thread::spawn(move || {
                let (mut stream, _) = listener.accept().expect("probe connects");
                let mut line = String::new();
                BufReader::new(stream.try_clone().expect("clone"))
                    .read_line(&mut line)
                    .expect("read request");
                assert!(line.contains("\"identify\""), "unexpected request: {line}");
                stream.write_all(reply.as_bytes()).expect("write reply");
            });

            let status = std::process::Command::new("python3")
                .arg(&script_path)
                .status()
                .expect("run the probe");
            server.join().expect("server thread");
            status.success()
        }

        assert!(run_probe("{\"ok\": true, \"protocol\": 1}\n"));
        assert!(!run_probe("{\"ok\": false, \"error\": \"nope\"}\n"));
    }

