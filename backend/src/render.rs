pub const CONFIG_HEADER: &str = "# Generated by fleett. Do not edit this file directly:\n\
# change the template and PATCH the instance instead.\n";

/// Health probe written to `instances/<id>/data/healthcheck.py` (mounted at
/// `/opt/data/healthcheck.py`).
///
/// The Hermes gateway exposes a Unix control socket at `$HERMES_HOME/gateway.sock`
/// (`/opt/data/gateway.sock` in the container). The probe sends one JSON line
/// and exits 0 only when the gateway answers `{"ok": true, ...}`. Stdlib only,
/// so it runs with the Python interpreter already present in the image.
pub const HEALTHCHECK_SCRIPT: &str = r#"#!/usr/bin/env python3
"""fleett health probe.

Asks the Hermes gateway to identify itself over its Unix control socket and
exits 0 only when the gateway answers with `"ok": true`.
"""

import json
import socket
import sys

SOCKET_PATH = "/opt/data/gateway.sock"
TIMEOUT_S = 3.0
REQUEST = {"verb": "identify", "id": 1, "protocol": 1}


def probe():
    sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    sock.settimeout(TIMEOUT_S)
    try:
        sock.connect(SOCKET_PATH)
        sock.sendall(json.dumps(REQUEST).encode("utf-8") + b"\n")
        received = b""
        while b"\n" not in received and len(received) < 65536:
            chunk = sock.recv(4096)
            if not chunk:
                break
            received += chunk
    finally:
        sock.close()

    line = received.split(b"\n", 1)[0].strip()
    if not line:
        return False
    reply = json.loads(line.decode("utf-8", "replace"))
    return isinstance(reply, dict) and reply.get("ok") is True


def main():
    try:
        return 0 if probe() else 1
    except (OSError, ValueError):
        return 1


if __name__ == "__main__":
    sys.exit(main())
"#;

#[derive(Debug, thiserror::Error)]
pub enum RenderError {
    #[error("unknown template \"{0}\"")]
    UnknownTemplate(String),
    #[error("invalid template YAML: {0}")]
    InvalidYaml(String),
    #[error("failed to render compose file: {0}")]
    Compose(String),
    #[error("invalid template: {0}")]
    Template(String),
    #[error("failed to read template: {0}")]
    Io(String),
}

/// A template as resolved through its inheritance chain.
#[derive(Debug, Clone)]
pub struct TemplateSource {
    pub id: String,
    pub config_yaml: String,
    pub soul_md: Option<String>,
    pub meta: TemplateMeta,
    /// Instance-creation defaults (`defaults.yaml`, merged with the parent).
    pub defaults: TemplateDefaults,
    /// Built-in templates are compiled constants and never modified.
    pub read_only: bool,
    /// `required` keys a custom template enforces when an instance is created.
    /// Inherited built-in allowlists stay warnings (#27).
    pub enforced_required: Vec<String>,
}

impl TemplateSource {
    /// Environment schema resolved through the template ancestry.
    pub fn env_schema(&self) -> Vec<crate::models::EnvSuggestion> {
        self.meta.env.clone().unwrap_or_default()
    }
}

/// Everything that has to be written for one instance.
#[derive(Debug, Clone)]
pub struct RenderedInstance {
    pub compose_yaml: String,
    pub config_yaml: String,
    pub soul_md: Option<String>,
}

/// Resolve a template through its inheritance chain.
///
/// Built-ins are authoritative (a directory may not shadow them); a custom
/// template is read from `$FLEETT_ROOT/templates/<id>` and merged with its
/// parent by [`crate::templates::resolve`].
pub fn load_template(cfg: &Config, id: &str) -> Result<TemplateSource, RenderError> {
    match crate::templates::resolve(cfg, id) {
        Ok(resolved) => Ok(TemplateSource {
            id: resolved.id,
            config_yaml: resolved.config_yaml,
            soul_md: resolved.soul_md,
            meta: resolved.meta,
            defaults: resolved.defaults,
            read_only: resolved.read_only,
            enforced_required: resolved.enforced_required,
        }),
        Err(crate::templates::TemplateError::NotFound(_)) => {
            Err(RenderError::UnknownTemplate(id.to_string()))
        }
        Err(err) => Err(RenderError::Template(err.to_string())),
    }
}

fn detected_channel(doc: Option<&Value>) -> Option<String> {
    let platforms = doc?.get("platforms")?;
    let enabled = |name: &str| {
        platforms
            .get(name)
            .and_then(|platform| platform.get("enabled"))
            .and_then(Value::as_bool)
            .unwrap_or(false)
    };
    if enabled("telegram") {
        Some(ChannelKind::Telegram.as_str().to_string())
    } else if enabled("discord") {
        Some(ChannelKind::Discord.as_str().to_string())
    } else {
        Some(ChannelKind::None.as_str().to_string())
    }
}

/// Render every generated file for an instance.
///
/// `env_keys` are the environment variable names the instance holds: they
/// are declared in the compose file as `${KEY}` and resolved by the driver at
/// runtime, so no secret value is ever written here.
pub fn render_instance(
    cfg: &Config,
    spec: &InstanceSpec,
    template: &TemplateSource,
    env_keys: &[String],
) -> Result<RenderedInstance, RenderError> {
    render_instance_with_project(cfg, spec, template, None, env_keys)
}

/// Same as [`render_instance`], keeping an explicit compose project name.
///
/// Updates pass the name already declared by the instance file, so an instance
/// created by an older release is never silently duplicated under a new
/// project name.
pub fn render_instance_with_project(
    cfg: &Config,
    spec: &InstanceSpec,
    template: &TemplateSource,
    project: Option<&str>,
    env_keys: &[String],
) -> Result<RenderedInstance, RenderError> {
    render_instance_with_project_and_policy(cfg, spec, template, project, env_keys, None)
}

/// Same as [`render_instance_with_project`] with the destination policy of the
/// instance, when it has one.
///
/// Only the compose document changes: a policy adds the proxy variables. The
/// Hermes `config.yaml` is untouched.
pub fn render_instance_with_project_and_policy(
    cfg: &Config,
    spec: &InstanceSpec,
    template: &TemplateSource,
    project: Option<&str>,
    env_keys: &[String],
    policy: Option<&EgressPolicy>,
) -> Result<RenderedInstance, RenderError> {
    Ok(RenderedInstance {
        compose_yaml: render_compose_with_project_and_policy(cfg, spec, project, env_keys, policy)?,
        config_yaml: render_config(spec, &template.config_yaml)?,
        soul_md: template.soul_md.as_ref().map(|soul| substitute(soul, spec)),
    })
}

/// Replace the four supported placeholders.
pub fn substitute(text: &str, spec: &InstanceSpec) -> String {
    text.replace("{{MODEL}}", &spec.model)
        .replace("{{BASE_URL}}", &spec.base_url)
        .replace("{{AGENT_NAME}}", &spec.name)
        .replace("{{API_KEY_ENV}}", &spec.api_key_env)
}

/// Render `data/config.yaml`.
///
/// The template is parsed and re-serialised so the model block always matches
/// the instance exactly and `platforms.<channel>.enabled` is always coherent,
/// even for hand-written templates.
pub fn render_config(spec: &InstanceSpec, template_yaml: &str) -> Result<String, RenderError> {
    let substituted = substitute(template_yaml, spec);
    let mut doc: Value = serde_yaml::from_str(&substituted)
        .map_err(|err| RenderError::InvalidYaml(err.to_string()))?;
    if !doc.is_mapping() {
        return Err(RenderError::InvalidYaml(
            "template root must be a YAML mapping".to_string(),
        ));
    }

    let model = child_mapping(&mut doc, "model");
    if let Value::Mapping(map) = model {
        map.insert(Value::from("default"), Value::from(spec.model.as_str()));
        map.insert(Value::from("provider"), Value::from("custom"));
        map.insert(Value::from("base_url"), Value::from(spec.base_url.as_str()));
        map.insert(
            Value::from("api_key"),
            Value::from(format!("${{{}}}", spec.api_key_env)),
        );
        map.insert(Value::from("api_mode"), Value::from("chat_completions"));
    }

    let platforms = child_mapping(&mut doc, "platforms");
    for name in ["telegram", "discord"] {
        if spec.channel.platform() == Some(name) {
            let entry = child_mapping(platforms, name);
            if let Value::Mapping(map) = entry {
                map.insert(Value::from("enabled"), Value::Bool(true));
            }
        } else if let Some(Value::Mapping(map)) = platforms.get_mut(name) {
            map.insert(Value::from("enabled"), Value::Bool(false));
        }
    }

    let body = serde_yaml::to_string(&doc).map_err(|err| RenderError::Compose(err.to_string()))?;
    Ok(format!("{CONFIG_HEADER}{body}"))
}

fn child_mapping<'a>(parent: &'a mut Value, key: &str) -> &'a mut Value {
    if !parent.is_mapping() {
        *parent = Value::Mapping(Mapping::new());
    }
    let replace = !matches!(parent.get(key), Some(Value::Mapping(_)));
    if replace {
        if let Value::Mapping(map) = parent {
            map.insert(Value::from(key), Value::Mapping(Mapping::new()));
        }
    }
    parent
        .get_mut(key)
        .expect("child mapping was created just above")
}

#[derive(Debug, Serialize)]
struct ComposeFile {
    name: String,
    services: BTreeMap<String, ComposeService>,
    networks: BTreeMap<String, ComposeNetwork>,
}

#[derive(Debug, Serialize)]
struct ComposeService {
    image: String,
    container_name: String,
    restart: String,
    command: Vec<String>,
    environment: BTreeMap<String, String>,
    volumes: Vec<String>,
    networks: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    labels: Option<BTreeMap<String, String>>,
    security_opt: Vec<String>,
    cap_drop: Vec<String>,
    tmpfs: Vec<String>,
    /// `read_only: true` only under `FLEETT_HARDENING=strict`; omitted
    /// otherwise so the standard compose file keeps its historical bytes.
    #[serde(skip_serializing_if = "Option::is_none")]
    read_only: Option<bool>,
    pids_limit: u32,
    mem_limit: String,
    memswap_limit: String,
    cpus: String,
    healthcheck: ComposeHealthcheck,
    logging: ComposeLogging,
}

#[derive(Debug, Serialize)]
struct ComposeHealthcheck {
    test: Vec<String>,
    interval: String,
    timeout: String,
    retries: u32,
    start_period: String,
}

#[derive(Debug, Serialize)]
struct ComposeLogging {
    driver: String,
    options: BTreeMap<String, String>,
}

#[derive(Debug, Serialize)]
struct ComposeNetwork {
    external: bool,
    name: String,
}

/// Compose project and container name of an instance created by this build.
///
/// Older releases declared `hermes-<id>`; the compose driver reads the project
/// back from the file so those instances keep working untouched.
pub fn project_name(id: &str) -> String {
    format!("fleett-{id}")
}

/// Render `instances/<id>/compose.yaml`.
///
/// No value ever appears in the document: every environment variable (secret
/// or not) is declared as `${KEY}` and resolved from the `docker compose`
/// process environment by the driver (`environment` is a Compose
/// interpolation, not a literal).
pub fn render_compose(
    cfg: &Config,
    spec: &InstanceSpec,
    env_keys: &[String],
) -> Result<String, RenderError> {
    render_compose_with_project(cfg, spec, None, env_keys)
}

/// Same as [`render_compose`] with an explicit project (and container) name.
pub fn render_compose_with_project(
    cfg: &Config,
    spec: &InstanceSpec,
    project: Option<&str>,
    env_keys: &[String],
) -> Result<String, RenderError> {
    render_compose_with_project_and_policy(cfg, spec, project, env_keys, None)
}

/// Same as [`render_compose_with_project`] with the instance destination
/// policy. A policy points the container at the operator-run egress proxy;
/// without one the compose bytes are exactly the historical ones.
pub fn render_compose_with_project_and_policy(
    cfg: &Config,
    spec: &InstanceSpec,
    project: Option<&str>,
    env_keys: &[String],
    policy: Option<&EgressPolicy>,
) -> Result<String, RenderError> {
    let project = project
        .map(str::to_string)
        .unwrap_or_else(|| project_name(&spec.id));
    let mut volumes = vec!["./data:/opt/data".to_string()];
    // The message bus mirrors every message as a JSON file; agents that cannot
    // call HTTP can read their inbox from `/opt/data/shared/bus/<id>/`.
    volumes.push("../../bus:/opt/bus".to_string());
    for share in &spec.shares {
        let read_only = if share.mode == ShareMode::Ro {
            ":ro"
        } else {
            ""
        };
        volumes.push(format!(
            "../../shares/{name}:/opt/data/shared/{name}{read_only}",
            name = share.name
        ));
    }

    let mut environment = BTreeMap::new();
    environment.insert("HERMES_UID".to_string(), "10000".to_string());
    environment.insert("HERMES_GID".to_string(), "10000".to_string());
    for key in env_keys {
        if crate::models::validate_secret_name(key).is_ok() {
            environment.insert(key.clone(), format!("${{{key}}}"));
        }
    }
    // A destination policy is enforced by the external proxy: point the agent
    // at it. Instances without a policy keep their historical bytes.
    if policy.is_some() {
        if let Some(proxy) = cfg.egress_proxy_url() {
            environment.insert("HTTP_PROXY".to_string(), proxy.to_string());
            environment.insert("HTTPS_PROXY".to_string(), proxy.to_string());
            environment.insert(
                "NO_PROXY".to_string(),
                egress_policy::no_proxy(&cfg.network),
            );
        }
    }

    let mut log_options = BTreeMap::new();
    log_options.insert("max-size".to_string(), "10m".to_string());
    log_options.insert("max-file".to_string(), "3".to_string());

    // The restricted network is always joined; `allow_lan` adds the
    // unrestricted one, which the host egress firewall does not filter.
    let mut service_networks = vec!["fleet".to_string()];
    let mut networks = BTreeMap::new();
    networks.insert(
        "fleet".to_string(),
        ComposeNetwork {
            external: true,
            name: cfg.network.clone(),
        },
    );
    if spec.allow_lan {
        service_networks.push("lan".to_string());
        networks.insert(
            "lan".to_string(),
            ComposeNetwork {
                external: true,
                name: cfg.lan_network(),
            },
        );
    }

    let (read_only, security_opt, cap_drop, tmpfs) = security_posture(cfg.hardening);

    let service = ComposeService {
        image: if spec.image.trim().is_empty() {
            cfg.image.clone()
        } else {
            spec.image.clone()
        },
        container_name: project.clone(),
        restart: "unless-stopped".to_string(),
        command: vec!["gateway".to_string(), "run".to_string()],
        environment,
        volumes,
        networks: service_networks,
        labels: spec
            .previous_image
            .as_deref()
            .map(str::trim)
            .filter(|image| !image.is_empty())
            .map(|image| {
                let mut labels = BTreeMap::new();
                labels.insert(
                    crate::store::PREVIOUS_IMAGE_LABEL.to_string(),
                    image.to_string(),
                );
                labels
            }),
        security_opt,
        cap_drop,
        tmpfs,
        read_only,
        pids_limit: 256,
        mem_limit: format!("{}m", spec.mem_limit_mb),
        memswap_limit: format!("{}m", spec.mem_limit_mb),
        cpus: format_cpu(spec.cpu_limit),
        healthcheck: ComposeHealthcheck {
            test: vec![
                "CMD".to_string(),
                "python3".to_string(),
                "/opt/data/healthcheck.py".to_string(),
            ],
            interval: "30s".to_string(),
            timeout: "5s".to_string(),
            retries: 3,
            start_period: "60s".to_string(),
        },
        logging: ComposeLogging {
            driver: "json-file".to_string(),
            options: log_options,
        },
    };

    let mut services = BTreeMap::new();
    services.insert("agent".to_string(), service);

    let compose = ComposeFile {
        name: project,
        services,
        networks,
    };

    serde_yaml::to_string(&compose).map_err(|err| RenderError::Compose(err.to_string()))
}

/// Security posture of the rendered service (`FLEETT_HARDENING`).
///
/// `standard` is what every release before issue #18 produced, byte for byte:
/// `no-new-privileges`, `NET_RAW` dropped, a single `/tmp` tmpfs. `strict` makes
/// the root filesystem read-only, drops every capability, mounts the three
/// scratch directories the Hermes entrypoint may touch, and keeps
/// `no-new-privileges` exactly once.
///
/// The image runs as root and drops to `HERMES_UID` through its s6 entrypoint,
/// which is why `/run` and `/var/tmp` must stay writable: see docs/HARDENING.md.
fn security_posture(hardening: Hardening) -> (Option<bool>, Vec<String>, Vec<String>, Vec<String>) {
    let no_new_privileges = vec!["no-new-privileges:true".to_string()];
    match hardening {
        Hardening::Standard => (
            None,
            no_new_privileges,
            vec!["NET_RAW".to_string()],
            vec!["/tmp".to_string()],
        ),
        Hardening::Strict => (
            Some(true),
            no_new_privileges,
            vec!["ALL".to_string()],
            ["/tmp", "/run", "/var/tmp"].map(str::to_string).to_vec(),
        ),
    }
}

/// Render a CPU quota the way Compose accepts it (`1`, `0.5`, `2.25`).
pub fn format_cpu(value: f64) -> String {
    value.to_string()
}

/// Build the contents of `secrets.env` for a new instance.
pub fn build_secrets(
    spec: &InstanceSpec,
    gate_token: Option<&str>,
    channel_token: Option<&str>,
    extras: &BTreeMap<String, String>,
) -> BTreeMap<String, String> {
    let mut secrets = extras.clone();
    if let Some(token) = gate_token {
        insert_gate_token(&mut secrets, spec, token);
    }
    if let Some(token) = channel_token {
        if let Some(env) = spec.channel.token_env() {
            secrets.insert(env.to_string(), token.to_string());
        }
    }
    secrets
}

/// Update the secrets of an existing instance without dropping tokens that the
/// request does not mention.
pub fn merge_secrets(
    mut secrets: BTreeMap<String, String>,
    spec: &InstanceSpec,
    gate_token: Option<&str>,
    channel_token: Option<&str>,
) -> BTreeMap<String, String> {
    if let Some(token) = gate_token {
        insert_gate_token(&mut secrets, spec, token);
    }
    for env in ChannelKind::all_platform_token_envs() {
        if spec.channel.token_env() != Some(env) {
            secrets.remove(env);
        }
    }
    if let Some(token) = channel_token {
        if let Some(env) = spec.channel.token_env() {
            secrets.insert(env.to_string(), token.to_string());
        }
    }
    secrets
}

fn insert_gate_token(secrets: &mut BTreeMap<String, String>, spec: &InstanceSpec, token: &str) {
    secrets.insert(GATE_TOKEN_ENV.to_string(), token.to_string());
    if spec.api_key_env != GATE_TOKEN_ENV && spec.api_key_env != DEFAULT_API_KEY_ENV {
        secrets.insert(spec.api_key_env.clone(), token.to_string());
    }
}

/// Used by the reconciler: read the channel back from a rendered config.
pub fn channel_from_config(doc: &Value) -> ChannelKind {
    detected_channel(Some(doc))
        .as_deref()
        .and_then(ChannelKind::parse)
        .unwrap_or(ChannelKind::None)
}

/// Used by the reconciler: read the model block back from a rendered config.
pub fn model_from_config(doc: &Value) -> (Option<String>, Option<String>, Option<String>) {
    let model = doc.get("model");
    let get = |key: &str| {
        model
            .and_then(|value| value.get(key))
            .and_then(Value::as_str)
            .map(str::to_string)
    };
    let api_key_env = get("api_key").and_then(|value| {
        value
            .strip_prefix("${")
            .and_then(|rest| rest.strip_suffix('}'))
            .map(str::trim)
            .filter(|name| !name.is_empty())
            .map(str::to_string)
    });
    (get("default"), get("base_url"), api_key_env)
}

