/// One prepared field of the context.
struct Field {
    label: &'static str,
    text: String,
}

fn is_binary(text: &str) -> bool {
    let mut control = 0usize;
    let mut total = 0usize;
    for ch in text.chars().take(4096) {
        total += 1;
        if ch == '\0' {
            return true;
        }
        if ch.is_control() && !matches!(ch, '\n' | '\r' | '\t') {
            control += 1;
        }
    }
    total > 0 && control * 10 > total
}

/// Truncate on a UTF-8 boundary.
fn truncate(text: &str, max: usize) -> String {
    if text.len() <= max {
        return text.to_string();
    }
    let mut end = max;
    while end > 0 && !text.is_char_boundary(end) {
        end -= 1;
    }
    format!("{}\n[truncated at {max} bytes]", &text[..end])
}

/// The instance environment split into redaction needles and a readable list.
fn env_secrets(
    cfg: &Config,
    db: &Db,
    instance: &str,
) -> Result<(Vec<String>, Vec<String>), AssistantError> {
    // Fail closed: without the decrypted values the redactor cannot remove
    // them, so the request is refused instead of leaking a secret.
    let entries = envs::load(cfg, db, instance)?;
    let secrets: Vec<String> = entries
        .iter()
        .filter(|entry| entry.secret)
        .map(|entry| entry.value.clone())
        .collect();
    let keys: Vec<String> = entries
        .iter()
        .filter(|entry| entry.secret)
        .map(|entry| entry.key.clone())
        .collect();
    Ok((secrets, keys))
}

/// Build the exact, redacted context sent to the provider.
///
/// `secrets` are extra literal values to scrub (the provider credential). The
/// secret environment values of `context.instance` are added automatically.
pub fn prepare_context(
    cfg: &Config,
    db: &Db,
    context: &ChatContext,
    secrets: &[String],
) -> Result<(String, Redaction), AssistantError> {
    let (instance_secrets, instance_keys) = match context.instance.as_deref() {
        Some(id) => env_secrets(cfg, db, id)?,
        None => (Vec::new(), Vec::new()),
    };
    let mut needles: Vec<String> = secrets.to_vec();
    needles.extend(instance_secrets);
    let redactor = Redactor::new(needles);

    let mut sent: Vec<String> = Vec::new();
    let mut omitted: Vec<String> = Vec::new();
    let mut redacted = 0usize;
    let mut fields: Vec<Field> = Vec::new();

    let page: String = context.page.chars().take(MAX_PAGE_CHARS).collect();
    let page = if page.trim().is_empty() {
        "unknown".to_string()
    } else {
        page
    };
    sent.push(format!("page: {page}"));

    if let Some(id) = context.instance.as_deref().filter(|id| !id.is_empty()) {
        sent.push(format!("instance: {id}"));
        if !instance_keys.is_empty() {
            omitted.push(format!(
                "env secrets: {} value(s) withheld ({})",
                instance_keys.len(),
                instance_keys.join(", ")
            ));
        }
    }
    if let Some(path) = context
        .path
        .as_deref()
        .filter(|path| !path.is_empty())
        .map(|path| path.chars().take(MAX_PATH_CHARS).collect::<String>())
    {
        sent.push(format!("path: {path}"));
        fields.push(Field {
            label: "path",
            text: path,
        });
    }
    for (label, value, max) in [
        (
            "selection",
            context.selection.as_deref(),
            MAX_SELECTION_BYTES,
        ),
        (
            "file_content",
            context.file_content.as_deref(),
            MAX_FILE_CONTENT_BYTES,
        ),
        ("schema", context.schema.as_deref(), MAX_SCHEMA_BYTES),
    ] {
        let Some(value) = value.filter(|value| !value.is_empty()) else {
            continue;
        };
        if is_binary(value) {
            omitted.push(format!("{label}: binary content withheld"));
            continue;
        }
        let (text, count) = redactor.redact(value);
        redacted += count;
        let truncated_from = (text.len() > max).then_some(value.len());
        let text = truncate(&text, max);
        sent.push(format!("{label}: {} bytes", text.len()));
        if let Some(original) = truncated_from {
            omitted.push(format!(
                "{label}: truncated to {max} bytes (was {original})"
            ));
        }
        fields.push(Field { label, text });
    }

    let mut body = format!("Page: {page}\n");
    if let Some(id) = context.instance.as_deref().filter(|id| !id.is_empty()) {
        body.push_str(&format!("Instance: {id}\n"));
    }
    for field in &fields {
        body.push_str(&format!("\n## {}\n{}\n", field.label, field.text));
    }
    let (body, extra) = redactor.redact(&body);
    redacted += extra;
    let body = truncate(&body, 4 * MAX_FILE_CONTENT_BYTES);

    Ok((
        body,
        Redaction {
            sent,
            omitted,
            redacted,
        },
    ))
}

