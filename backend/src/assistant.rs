//! Integrated assistant (issue #56).
//!
//! The assistant is a drafting tool for the console: it answers with a short
//! explanation and, when the operator asked for something applicable, one
//! [`Proposal`] (a file, a YAML document or a list of environment variables).
//! The console applies the proposal through the regular routes — file ETag,
//! backup, git commit and audit included — so the assistant itself never
//! writes anything.
//!
//! ## Configuration
//!
//! | Variable | Meaning |
//! |---|---|
//! | `FLEETT_ASSISTANT` | `on` (default) or `off`; `off` removes both routes |
//! | `FLEETT_ASSISTANT_PROVIDER` | id of the provider that answers |
//! | `FLEETT_ASSISTANT_MODEL` | model name (`deepseek-v4.1-flash` by default) |
//! | `FLEETT_ASSISTANT_BUDGET_TOKENS` | per-session token budget, `0` disables |
//! | `FLEETT_ASSISTANT_MAX_OUTPUT_TOKENS` | output ceiling (`4096` by default), `0` lets the provider decide |
//!
//! ## Redaction
//!
//! Every payload is redacted before it leaves the process:
//!
//! * the provider secret and every secret environment value of the instance in
//!   scope are replaced by `[REDACTED]`;
//! * token shapes (`sk-…`, `flt_…`, `Bearer …`) are replaced by `[REDACTED]`;
//! * binary content is never sent, and `file_content`, `selection` and `schema`
//!   are capped (32 KiB, 8 KiB, 8 KiB).
//!
//! The response reports what was sent and what was withheld in
//! [`Redaction`], so the console can show the exact contract to the operator.

