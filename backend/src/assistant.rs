/// One prepared chat-completion call. The secret only lives in `headers`.
#[derive(Debug, Clone)]
pub struct PreparedCall {
    pub url: String,
    pub headers: Vec<(String, String)>,
    pub body: Value,
}

/// Build `${base_url}/chat/completions` for an OpenAI-compatible provider.
pub fn prepare_chat(
    provider: &ProviderSpec,
    secret: &str,
    model: &str,
    system: &str,
    messages: &[ChatMessage],
) -> PreparedCall {
    let mut outgoing = Vec::with_capacity(messages.len() + 1);
    outgoing.push(json!({"role": "system", "content": system}));
    for message in messages {
        outgoing.push(json!({"role": message.role, "content": message.content}));
    }
    PreparedCall {
        url: format!(
            "{}/chat/completions",
            provider.base_url.trim_end_matches('/')
        ),
        headers: vec![
            ("authorization".to_string(), format!("Bearer {secret}")),
            ("content-type".to_string(), "application/json".to_string()),
        ],
        body: json!({
            "model": model,
            "messages": outgoing,
            "temperature": TEMPERATURE,
            "max_tokens": MAX_REPLY_TOKENS,
        }),
    }
}

/// One parsed provider answer.
#[derive(Debug, Clone)]
pub struct Completion {
    pub text: String,
    pub prompt_tokens: u64,
    pub completion_tokens: u64,
}

/// Conservative token estimate (four characters per token).
pub fn estimate_tokens(text: &str) -> u64 {
    (text.chars().count() as u64).div_ceil(4)
}

/// Send one completion request. The provider error body is never echoed.
pub async fn complete(call: &PreparedCall) -> Result<Completion, AssistantError> {
    tracing::debug!(
        url = %call.url,
        body = %call.body,
        "assistant provider request (redacted)"
    );
    let client = reqwest::Client::builder()
        .timeout(REQUEST_TIMEOUT)
        .build()
        .map_err(|err| AssistantError::Provider(err.to_string()))?;
    let mut request = client.post(&call.url);
    for (name, value) in &call.headers {
        request = request.header(name, value);
    }
    let response = request.json(&call.body).send().await.map_err(|err| {
        if err.is_timeout() {
            AssistantError::Provider(format!(
                "the provider did not answer within {}s",
                REQUEST_TIMEOUT.as_secs()
            ))
        } else if err.is_connect() {
            AssistantError::Provider("the provider is unreachable".to_string())
        } else {
            AssistantError::Provider("the request failed".to_string())
        }
    })?;
    let status = response.status();
    if !status.is_success() {
        let _ = response.bytes().await;
        return Err(AssistantError::ProviderStatus(status.as_u16()));
    }
    let value: Value = response
        .json()
        .await
        .map_err(|_| AssistantError::BadPayload)?;
    parse_completion(&value)
}

/// Parse one OpenAI-compatible completion payload.
pub fn parse_completion(value: &Value) -> Result<Completion, AssistantError> {
    let text = value
        .pointer("/choices/0/message/content")
        .and_then(Value::as_str)
        .map(str::to_string)
        .filter(|text| !text.trim().is_empty())
        .ok_or(AssistantError::BadPayload)?;
    let prompt_tokens = value
        .pointer("/usage/prompt_tokens")
        .and_then(Value::as_u64)
        .unwrap_or(0);
    let completion_tokens = value
        .pointer("/usage/completion_tokens")
        .and_then(Value::as_u64)
        .unwrap_or(0);
    Ok(Completion {
        text,
        prompt_tokens,
        completion_tokens,
    })
}

