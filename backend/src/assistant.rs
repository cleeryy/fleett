/// In-memory token counters, one per session id.
///
/// A restart forgets everything, which is the documented contract: the counter
/// guards one conversation, not a billing period.
#[derive(Debug, Default)]
pub struct Sessions {
    spent: Mutex<HashMap<String, u64>>,
}

impl Sessions {
    fn lock(&self) -> std::sync::MutexGuard<'_, HashMap<String, u64>> {
        self.spent
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Tokens already spent in one session.
    pub fn used(&self, session_id: &str) -> u64 {
        self.lock().get(session_id).copied().unwrap_or(0)
    }

    /// Account for one turn and return the new total of the session.
    pub fn add(&self, session_id: &str, tokens: u64) -> u64 {
        let mut map = self.lock();
        let entry = map.entry(session_id.to_string()).or_insert(0);
        *entry = entry.saturating_add(tokens);
        *entry
    }

    /// Sum of every live session (reported when `/config` has no session id).
    pub fn total(&self) -> u64 {
        self.lock()
            .values()
            .copied()
            .fold(0u64, u64::saturating_add)
    }
}

/// Whether one more turn fits in the budget.
///
/// The whole reply ceiling plus the prompt has to fit: a budget smaller than
/// one answer can never produce one, which is what `0` (disabled) is for. When
/// `FLEETT_ASSISTANT_MAX_OUTPUT_TOKENS=0` the provider decides; the budget then
/// reserves [`DEFAULT_MAX_OUTPUT_TOKENS`], the shipped default.
pub fn budget_allows(budget: u64, used: u64, prompt_tokens: u64, max_output_tokens: u64) -> bool {
    if budget == 0 {
        return true;
    }
    let allowance = if max_output_tokens == 0 {
        DEFAULT_MAX_OUTPUT_TOKENS
    } else {
        max_output_tokens
    };
    used.saturating_add(prompt_tokens).saturating_add(allowance) <= budget
}

