/// Strip one surrounding Markdown code fence, if present.
fn strip_fence(text: &str) -> &str {
    let trimmed = text.trim();
    let Some(rest) = trimmed.strip_prefix("```") else {
        return trimmed;
    };
    let rest = rest.split_once('\n').map(|(_, body)| body).unwrap_or(rest);
    rest.strip_suffix("```").unwrap_or(rest).trim()
}

fn valid_path(path: &str) -> bool {
    if !path.starts_with('/') || path.len() > MAX_PATH_CHARS || path.contains("..") {
        return false;
    }
    if path.chars().any(|ch| ch.is_control()) {
        return false;
    }
    let name = path.rsplit('/').next().unwrap_or("");
    !RENDERED_FILES.contains(&name)
}

fn env_key_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[A-Za-z_][A-Za-z0-9_]{0,127}$").expect("valid regex"))
}

/// Validate one proposal coming from the model. An invalid proposal is dropped
/// instead of failing the whole answer: the explanation stays readable.
pub fn validate_proposal(value: &Value) -> Option<Proposal> {
    let kind = value.get("kind")?.as_str()?.trim().to_ascii_lowercase();
    match kind.as_str() {
        "file" | "yaml" => {
            // A `file` always names its target; a `yaml` snippet may be
            // copy-only, in which case the console shows it without applying.
            let path = match value.get("path").and_then(Value::as_str) {
                Some(path) => {
                    let path = path.trim().to_string();
                    if !valid_path(&path) {
                        return None;
                    }
                    Some(path)
                }
                None if kind == "yaml" => None,
                None => return None,
            };
            let content = value.get("content")?.as_str()?.to_string();
            if content.trim().is_empty() || content.len() > 512 * 1024 {
                return None;
            }
            Some(Proposal {
                kind,
                path,
                content: Some(content),
                env: None,
            })
        }
        "env" => {
            let entries = value.get("env")?.as_array()?;
            let mut env = Vec::new();
            for entry in entries.iter().take(200) {
                let Some(key) = entry.get("key").and_then(Value::as_str) else {
                    continue;
                };
                let key = key.trim();
                if !env_key_regex().is_match(key) {
                    continue;
                }
                let value = entry
                    .get("value")
                    .and_then(Value::as_str)
                    .map(str::to_string);
                if value.as_deref().is_some_and(|value| value.len() > 4 * 1024) {
                    continue;
                }
                let secret = entry
                    .get("secret")
                    .and_then(Value::as_bool)
                    .unwrap_or(false);
                env.push(ProposalEnvEntry {
                    key: key.to_string(),
                    value,
                    secret,
                });
            }
            (!env.is_empty()).then_some(Proposal {
                kind,
                path: None,
                content: None,
                env: Some(env),
            })
        }
        _ => None,
    }
}

/// Parse the model answer: a JSON object `{message, proposal?}`, or the raw
/// text when the model did not honour the contract.
pub fn parse_reply(text: &str) -> (String, Option<Proposal>) {
    let candidate = strip_fence(text);
    if let Ok(Value::Object(object)) = serde_json::from_str::<Value>(candidate) {
        if let Some(message) = object.get("message").and_then(Value::as_str) {
            let proposal = object.get("proposal").and_then(validate_proposal);
            return (message.to_string(), proposal);
        }
    }
    (text.trim().to_string(), None)
}

