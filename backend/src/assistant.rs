/// What the operator is trying to produce.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Task {
    /// A `SKILL.md` draft.
    #[serde(alias = "write_skill", alias = "write-skill")]
    Skill,
    /// A `SOUL.md` draft.
    #[serde(alias = "draft_soul", alias = "draft-soul")]
    Soul,
    /// Environment variables with plausible values.
    #[serde(alias = "env_allowlist", alias = "env-allowlist")]
    Env,
    /// A `fleet.yaml` or pipeline document.
    Yaml,
    /// Explain an error, a log excerpt or a `last_error`.
    #[serde(alias = "explain_error", alias = "explain-error")]
    Explain,
    /// Advice on the `config.yaml` fleett renders from the instance settings.
    #[serde(alias = "config_yaml", alias = "config-yaml")]
    Config,
    /// Anything else.
    #[default]
    Freeform,
}

impl Task {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Skill => "skill",
            Self::Soul => "soul",
            Self::Env => "env",
            Self::Yaml => "yaml",
            Self::Explain => "explain",
            Self::Config => "config",
            Self::Freeform => "freeform",
        }
    }

    fn instructions(self) -> &'static str {
        match self {
            Self::Skill => {
                "Draft a SKILL.md. Start with YAML front matter holding `name` (kebab-case) and \
                 `description` (at most 60 characters). Then the procedure as numbered steps, then \
                 a `## Pitfalls` section. Propose the file with kind `file`."
            }
            Self::Soul => {
                "Draft a SOUL.md with four short sections in this order: Identity, Tone, Scope, \
                 Refusals. Propose the file with kind `file`."
            }
            Self::Env => {
                "Propose environment variables with kind `env`. Use plausible values for \
                 allowlists (for example a comma-separated list of ids), never a credential: \
                 leave `value` out and set `secret: true` for anything the operator must fill in."
            }
            Self::Yaml => {
                "Propose a complete, valid YAML document (fleet.yaml or a pipeline) with kind \
                 `yaml`. It must parse: no tabs, no comment-only body, no ellipsis."
            }
            Self::Explain => {
                "Explain the failure in plain language: cause, impact, then the fix. Only propose \
                 a change when the fix is a configuration edit, and keep the explanation short."
            }
            Self::Config => {
                "Write the Hermes `config.yaml` for the requested model and channel as a \
                 copy-only YAML proposal (kind `yaml`, no `path`). fleett renders the deployed \
                 `config.yaml` from the instance settings, so explain in `message` which setting \
                 (model, provider, channel) produces it; never propose the file itself."
            }
            Self::Freeform => "",
        }
    }
}

