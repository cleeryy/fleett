import type { SkillFile, SkillRef, SkillRefDetail } from "@/api/types";
import { isValidSlug } from "@/lib/validation";

/**
 * Shared skills (issue #54). The registry is one directory tree the controller
 * mounts read-only; this module holds the browser-side mirror of its grammar
 * and limits, so a form refuses the same input the controller would.
 */

/** Most skills one instance may mount (`MAX_SKILLS_PER_INSTANCE`). */
export const MAX_SKILLS_PER_INSTANCE = 32;
/** Longest accepted skill description. */
export const MAX_SKILL_DESCRIPTION = 4096;
/** Most files one version may contain. */
export const MAX_SKILL_FILES = 256;
/** Bytes per file and per version, as enforced by the controller. */
export const MAX_SKILL_FILE_BYTES = 256 * 1024;
export const MAX_SKILL_VERSION_BYTES = 1024 * 1024;
/** Largest accepted zip upload. */
export const MAX_SKILL_ZIP_BYTES = 8 * 1024 * 1024;
/** Generated by the registry: a publish that names them is refused. */
export const RESERVED_SKILL_PATHS = ["skill.yaml", "latest"] as const;
/** Name of the mandatory entry file. */
export const SKILL_FILE = "SKILL.md";

/** Radix Select forbids an empty item value; callers map this back to no pin. */
export const FOLLOW_LATEST = "latest";

export const SKILL_VERSION_RE = /^v[1-9][0-9]{0,8}$/;

/** UTF-8 size of a string, the unit every registry limit uses. */
export function byteLength(value: string): number {
  return new TextEncoder().encode(value).length;
}

export function isValidSkillName(value: string): boolean {
  return isValidSlug(value);
}

export function isValidSkillVersion(value: string): boolean {
  return SKILL_VERSION_RE.test(value);
}

/** `v1`, `v2`, … → the version a new publish should suggest. */
export function nextSkillVersion(versions: string[]): string {
  let highest = 0;
  for (const version of versions) {
    if (!isValidSkillVersion(version)) continue;
    highest = Math.max(highest, Number(version.slice(1)));
  }
  return `v${highest + 1}`;
}

/** The version a pin resolves to, mirroring the controller's `effective_version`. */
export function effectiveVersion(
  ref: SkillRef,
  versions: string[],
  latest: string | null,
): string | null {
  if (ref.version) return versions.includes(ref.version) ? ref.version : null;
  return latest;
}

/** One declared skill → the wire shape. A missing version means "follow latest". */
export function skillRefPayload(refs: SkillRef[]): SkillRef[] {
  return refs.map((ref) => ({
    name: ref.name,
    ...(ref.version ? { version: ref.version } : {}),
  }));
}

/** Server detail → editable pin list: `null` is the explicit "follow latest". */
export function skillRefsFromDetail(refs: SkillRefDetail[] | undefined): SkillRef[] {
  return (refs ?? []).map((ref) => ({ name: ref.name, version: ref.version ?? null }));
}

/** `true` when the list is over the instance bound. */
export function tooManySkills(refs: SkillRef[]): boolean {
  return refs.length > MAX_SKILLS_PER_INSTANCE;
}

/**
 * One relative file path of a version. Mirrors the controller: relative, no
 * `..`, no backslash, no NUL, components of 64 characters, 200 in total.
 */
export function skillPathError(
  path: string,
  t: (key: string, params?: Record<string, string | number>) => string,
): string | null {
  if (!path) return t("skills.files.pathRequired");
  if (path.length > 200) return t("skills.files.pathTooLong");
  if (path.includes("\0")) return t("skills.files.pathNul");
  if (path.includes("\\")) return t("skills.files.pathBackslash");
  if (path.startsWith("/")) return t("skills.files.pathRelative");
  for (const component of path.split("/")) {
    if (!component) return t("skills.files.pathEmptyComponent");
    if (component === "." || component === "..") return t("skills.files.pathDots");
    if (component.length > 64) return t("skills.files.pathComponentTooLong");
  }
  if ((RESERVED_SKILL_PATHS as readonly string[]).includes(path)) {
    return t("skills.files.pathReserved", { path });
  }
  return null;
}

export interface SkillFileRow {
  id: string;
  path: string;
  content: string;
}

/** An empty row for the publish form. */
export function newSkillFileRow(id: string, path = "", content = ""): SkillFileRow {
  return { id, path, content };
}

/** Example shown in the empty SKILL.md editor; technical Markdown, not UI copy. */
export const SKILL_PLACEHOLDER = "# Skill name\n\nUse this skill when…";

/** Content of a brand-new `SKILL.md`, offered as a starting point. */
export const SKILL_SKELETON = [
  "# Skill name",
  "",
  "Use this skill when the request touches <topic>.",
  "",
  "## Steps",
  "1. Read the notes that ship with this skill.",
  "2. Check the facts before acting.",
  "3. Report what changed, and what was left alone.",
  "",
  "## Pitfalls",
  "- Guessing a value that is written down elsewhere in the fleet.",
  "- Running a destructive command without a confirmation.",
  "",
].join("\n");

/** `true` when the file exists in the version and is Markdown (`SKILL.md`). */
export function isMarkdownSkillFile(path: string): boolean {
  return path.toLowerCase().endsWith(".md");
}

/** Paths of a version, sorted with `SKILL.md` first then alphabetically. */
export function sortedSkillPaths(files: SkillFile[]): string[] {
  return files
    .map((file) => file.path)
    .sort((left, right) => {
      if (left === SKILL_FILE) return -1;
      if (right === SKILL_FILE) return 1;
      return left.localeCompare(right);
    });
}
